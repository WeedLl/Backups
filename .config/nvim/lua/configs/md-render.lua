-- ============================================================
-- md-render.nvim: конфигурация и кеймапы
-- ============================================================

-- Плагин не имеет традиционного setup() — работает из коробки.
-- Если понадобится тонкая настройка (например, PlantUML-сервер),
-- её можно добавить здесь через require("md-render").setup({...})

-- ============================================================
-- Кеймапы
-- ============================================================

-- <leader>mp — плавающее окно предпросмотра (поведение по умолчанию)
vim.keymap.set("n", "<leader>m", "<cmd>MdRender<cr>", { desc = "MdRender: Float preview" })
-- ============================================================
-- Автопредпросмотр при запуске `nvim file.md`
-- ============================================================

vim.api.nvim_create_autocmd("VimEnter", {
	group = vim.api.nvim_create_augroup("MdRenderAutoPreview", { clear = true }),
	callback = function()
		-- Срабатывает, только если Neovim запущен ровно с одним .md файлом
		if vim.fn.argc() == 1 and vim.bo.filetype == "markdown" then
			-- Небольшая задержка, чтобы UI успел отрисоваться
			vim.defer_fn(function()
				vim.cmd("MdRender")
			end, 100)
		end
	end,
})
